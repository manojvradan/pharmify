/**
 * Writes lib/cases/index.generated.ts: one import per file in data/cases/. Used by
 * `npm run cases:index` (scripts/gen-case-index.mts, also run before every build) and by
 * the WhatsApp bot, which commits a new case together with the regenerated index.
 * No imports, so plain Node can load this file.
 */

export const CASE_INDEX_PATH = "lib/cases/index.generated.ts";

export function caseFilenames(names: string[]): string[] {
  return names.filter((n) => /^[a-z0-9-]+\.json$/.test(n)).sort();
}

export function renderCaseIndex(names: string[]): string {
  const files = caseFilenames(names);
  const ident = (f: string) => `case_${f.replace(/\.json$/, "").replace(/-/g, "_")}`;
  return `// Generated by \`npm run cases:index\` from data/cases/*.json. Don't edit by hand.
${files.map((f) => `import ${ident(f)} from "@/data/cases/${f}";`).join("\n")}

export const RAW_CASES: unknown[] = [
${files.map((f) => `  ${ident(f)},`).join("\n")}
];
`;
}
